#!/bin/sh
# Writes the Kustomize overlay for the "release" flavor of the Zarf package.
# It points the Deployment at a published image by digest, so the package and
# the manifests reference exactly the image that was built and signed.
# Usage: sh scripts/release-overlay.sh REGISTRY/REPOSITORY@sha256:DIGEST
set -eu

ref="${1:?usage: release-overlay.sh REGISTRY/REPOSITORY@sha256:DIGEST}"
case "$ref" in
    *@sha256:????????????????????????????????????????????????????????????????) ;;
    *) echo "release-overlay: image must be pinned by sha256 digest: $ref" >&2; exit 1 ;;
esac
name="${ref%@*}"
digest="${ref#*@}"

mkdir -p deploy/zarf/release-overlay
cat > deploy/zarf/release-overlay/kustomization.yaml <<OVERLAY
# Generated by scripts/release-overlay.sh; not committed.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../overlay
images:
  - name: platform-engineering-lab
    newName: $name
    digest: $digest
OVERLAY
echo "release overlay -> $name@$digest"
